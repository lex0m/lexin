package io.github.lex0m.lexin;

import java.util.HashMap;
import java.util.Map;

/**
 * 每个功能「要做什么操作才会命中」。
 *
 * 为什么需要这张表（v1.7）：
 *   面板原来只有两种颜色 —— 命中=绿，其它=橙。于是「已挂载 2 处，未命中」和「没适配」
 *   长得一模一样，用户看到满屏橙色就以为模块全坏了。实测 2026-11-16 的真机面板：
 *   18 项里 16 项橙，而其中 14 项只是"还没触发"（hook 活性 hits=57 证明机制是好的）。
 *
 *   这里给每一项补一句"怎么才能让它命中"，让 ARMED 变成可理解的状态，而不是疑似故障。
 */
final class Triggers {

    private static final Map<String, String> MAP = new HashMap<>();

    static {
        MAP.put("去广告", "打开小程序或朋友圈，遇到广告位时命中");
        MAP.put("运动步数", "开这个开关后重启微信；仅走路/摇动手机时才会改写步数");
        MAP.put("骰子/猜拳", "聊天里打开表情面板，点骰子或猜拳时命中");
        MAP.put("悬浮聊天底栏", "进任意聊天页（发一条消息更稳）");
        MAP.put("自动查看原图", "在聊天里点开一张图片，等「查看原图」按钮出现");
        MAP.put("隐蔽入口", "长按关怀模式「开启」/ LSPosed 的 ▶ / 桌面图标");
        MAP.put("hook 活性", "微信切回前台就会命中（这一项绿 = hook 框架正常）");
        MAP.put("批量分类标签", "通讯录 → 标签 → 选好友批量分类");
        MAP.put("放宽本地限制", "添加超过默认上限的表情包，或长按消息多选");
        MAP.put("消息防撤回", "等对方撤回一条消息");
        MAP.put("撤回标记", "等对方撤回一条消息（气泡旁应出现标签）");
        MAP.put("朋友圈保留", "等对方删除一条朋友圈动态或评论");
        MAP.put("环境隐蔽", "微信启动时的自检跑过一次就会命中");
        MAP.put("转发增强", "长按任意一条消息，看菜单里有没有「转发（乐信）」");
        MAP.put("主页悬浮底栏", "回到微信主界面（四个 tab 那一页）");
        MAP.put("解除扫码限制", "从相册选二维码扫，或长按图片识别");
        MAP.put("数据库兜底", "撤回消息改写数据库时才会命中（和防撤回同一条链路）");
        MAP.put("自动语音转文字", "收到一条语音消息（开关默认关，开了要重启微信）");
    }

    /** 触发条件；没有登记的功能返回 null（面板就不显示第二行）。 */
    static String of(String feature) {
        return MAP.get(feature);
    }

    private Triggers() {}
}
